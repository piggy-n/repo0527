// 只供测试：合成的网格和轨迹
import type { Vec3 } from './lcc2-data.ts';
import type { Mesh } from './ply.ts';

/** 水平的矩形，两个三角形；slope 是沿 x 每米升高多少 */
export function rectangle(x0: number, y0: number, x1: number, y1: number, z: number, slope = 0): Mesh {
  const at = (x: number) => z + (x - x0) * slope;
  return {
    positions: Float32Array.from([x0, y0, at(x0), x1, y0, at(x1), x1, y1, at(x1), x0, y1, at(x0)]),
    triangles: Uint32Array.from([0, 1, 2, 0, 2, 3])
  };
}

/** 网格整体平移 */
export function translate(mesh: Mesh, [dx, dy, dz]: Vec3): Mesh {
  const positions = mesh.positions.map((value, index) => value + [dx, dy, dz][index % 3]);
  return { positions, triangles: mesh.triangles };
}

interface Segment {
  readonly from: readonly [number, number];
  readonly to: readonly [number, number];
}

/** 沿折线每隔 step 米一个点，高度由 floorAt 加上手持的高度 */
export function walk(segments: readonly Segment[], floorAt: (x: number, y: number) => number, hold = 1.25, step = 0.1) {
  const points: Vec3[] = [];
  for (const { from, to } of segments) {
    const length = Math.hypot(to[0] - from[0], to[1] - from[1]);
    for (let s = 0; s <= length; s += step) {
      const x = from[0] + ((to[0] - from[0]) * s) / length;
      const y = from[1] + ((to[1] - from[1]) * s) / length;
      points.push([x, y, floorAt(x, y) + hold]);
    }
  }
  return points;
}

/** 二进制小端的 PLY：顶点是 float 的 x、y、z（可以多带 extra 个 float 属性），面是 uchar 个数加 int 序号 */
export function plyBytes(positions: readonly number[], faces: readonly (readonly number[])[], extra = 0): Uint8Array {
  const vertexCount = positions.length / 3;
  const header = [
    'ply',
    'format binary_little_endian 1.0',
    'comment generated by test',
    `element vertex ${vertexCount}`,
    'property float x',
    'property float y',
    'property float z',
    ...Array.from({ length: extra }, (_, index) => `property float extra${index}`),
    `element face ${faces.length}`,
    'property list uchar int vertex_indices',
    'end_header',
    ''
  ].join('\n');
  const head = new TextEncoder().encode(header);
  const size = head.length + vertexCount * (3 + extra) * 4 + faces.reduce((sum, face) => sum + 1 + face.length * 4, 0);
  const bytes = new Uint8Array(size);
  bytes.set(head);
  const view = new DataView(bytes.buffer);
  let offset = head.length;
  for (let i = 0; i < vertexCount; i++) {
    for (let k = 0; k < 3; k++) {
      view.setFloat32(offset, positions[i * 3 + k], true);
      offset += 4;
    }
    for (let k = 0; k < extra; k++) {
      view.setFloat32(offset, 99, true);
      offset += 4;
    }
  }
  for (const face of faces) {
    view.setUint8(offset, face.length);
    offset += 1;
    for (const index of face) {
      view.setInt32(offset, index, true);
      offset += 4;
    }
  }
  return bytes;
}
